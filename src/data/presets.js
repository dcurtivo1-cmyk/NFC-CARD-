export const themes = templateDefinitions.map(
  ([
    id,
    name,
    paletteId,
    headerLayout,
    buttonLayout,
    backgroundStyle,
    iconStyle,
    font,
    radius,
    buttonStyle,
    category,
    description,
  ]) => {
    const palette = colorPalettes.find((item) => item.id === paletteId);
    return {
      ...designDefaults,
      ...palette,
      id,
      name,
      templateStyle: id,
      category,
      description,
      headerLayout,
      buttonLayout,
      backgroundStyle,
      iconStyle,
      font,
      radius,
      buttonStyle,
      cover: coverGradient(palette),
    };
  },
);

